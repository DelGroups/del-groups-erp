#!/usr/bin/env python3
"""Turn supabase/baseline/live-catalog.json into the ordered baseline SQL files.

The catalog is produced by supabase/baseline/catalog.sql (read-only) against the
production database. Run from the repo root:

    python3 scripts/db/generate-baseline.py

Every generated file is safe to re-run on a database that was built from it.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / "supabase" / "baseline"
CATALOG = BASE / "live-catalog.json"
SEED = BASE / "seed-data.json"

HEADER = "-- Generated by scripts/db/generate-baseline.py from live-catalog.json. Do not edit by hand.\n"


def q(name):
    """Quote an identifier only when it needs it."""
    if re.fullmatch(r"[a-z_][a-z0-9_$]*", name) and name not in RESERVED:
        return name
    return '"' + name.replace('"', '""') + '"'


# Postgres reserved and type/function-name keywords: these need quotes as identifiers.
RESERVED = set("""
all analyse analyze and any array as asc asymmetric both case cast check collate column constraint create
current_catalog current_date current_role current_time current_timestamp current_user default deferrable desc
distinct do else end except false fetch for foreign from grant group having in initially intersect into lateral
leading limit localtime localtimestamp not null offset on only or order placing primary references returning
select session_user some symmetric system_user table then to trailing true union unique user using variadic when
where window with authorization binary collation concurrently cross current_schema freeze full ilike inner is
isnull join left like natural notnull outer overlaps right similar tablesample verbose
""".split())


def lit(s):
    return "'" + s.replace("'", "''") + "'"


def dollar(body, tag="q"):
    t = tag
    while f"${t}$" in body:
        t += "x"
    return f"${t}${body}${t}$"


def load():
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    if isinstance(data, list):
        data = data[0]
    if "catalog" in data:
        data = data["catalog"]
    for k, v in list(data.items()):
        if v is None:
            data[k] = []
    return data


def write(name, parts):
    path = BASE / name
    path.write_text(HEADER + "\n".join(parts).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size} bytes)")


def extensions():
    return [
        "create schema if not exists extensions;",
        'create extension if not exists "pgcrypto" with schema extensions;',
        'create extension if not exists "uuid-ossp" with schema extensions;',
        "",
    ]


def types(c):
    out = []
    for e in c["enums"]:
        labels = ", ".join(lit(x) for x in e["labels"])
        out.append(
            "do $$ begin\n"
            f"  if not exists (select 1 from pg_type where typname = {lit(e['n'])} and typnamespace = 'public'::regnamespace) then\n"
            f"    create type public.{q(e['n'])} as enum ({labels});\n"
            "  end if;\nend $$;"
        )
    for d in c["domains"]:
        body = f"create domain public.{q(d['n'])} as {d['base']}"
        if d["def"]:
            body += f" default {d['def']}"
        if d["notnull"]:
            body += " not null"
        for chk in d["checks"] or []:
            body += f" {chk}"
        out.append(
            "do $$ begin\n"
            f"  if not exists (select 1 from pg_type where typname = {lit(d['n'])} and typnamespace = 'public'::regnamespace) then\n"
            f"    {body};\n  end if;\nend $$;"
        )
    for t in c["composites"]:
        cols = ", ".join(f"{q(a['n'])} {a['t']}" for a in t["cols"])
        out.append(
            "do $$ begin\n"
            f"  if not exists (select 1 from pg_type where typname = {lit(t['n'])} and typnamespace = 'public'::regnamespace) then\n"
            f"    create type public.{q(t['n'])} as ({cols});\n  end if;\nend $$;"
        )
    return out


def sequences(c):
    out = []
    for s in c["sequences"]:
        if s["identity"]:
            continue
        out.append(
            f"create sequence if not exists public.{q(s['n'])} as {s['type']} "
            f"increment by {s['inc']} minvalue {s['min']} maxvalue {s['max']} start with {s['start']} "
            f"cache {s['cache']}{' cycle' if s['cycle'] else ' no cycle'};"
        )
    return out


def tables(c):
    out = []
    for t in c["tables"]:
        cols = []
        for a in t["cols"]:
            line = f"  {q(a['n'])} {a['t']}"
            if a["gen"] == "s":
                line += f" generated always as ({a['def']}) stored"
            if a["id"] in ("a", "d"):
                line += " generated " + ("always" if a["id"] == "a" else "by default") + " as identity"
            if a["nn"]:
                line += " not null"
            cols.append(line)
        opts = f" with ({', '.join(t['opts'])})" if t["opts"] else ""
        part = f" partition by {t['partkey']}" if t.get("partkey") else ""
        out.append(f"create table if not exists public.{q(t['n'])} (\n" + ",\n".join(cols) + f"\n){part}{opts};\n")
    return out


def functions(c):
    out = ["set check_function_bodies = off;", ""]
    for f in c["functions"]:
        out.append(f["def"].rstrip() + ";\n")
    return out


def defaults(c):
    out = []
    for t in c["tables"]:
        for a in t["cols"]:
            if a["def"] is not None and not a["gen"]:
                out.append(f"alter table only public.{q(t['n'])} alter column {q(a['n'])} set default {a['def']};")
    for s in c["sequences"]:
        if s["owned"] and not s["identity"]:
            out.append(f"alter sequence public.{q(s['n'])} owned by public.{q(s['owned']['t'])}.{q(s['owned']['c'])};")
    return out


def constraints(c):
    order = {"p": 0, "u": 1, "x": 2, "c": 3, "f": 4}
    rows = sorted(c["constraints"], key=lambda r: (order[r["type"]], r["t"], r["n"]))
    out = []
    for r in rows:
        stmt = f"alter table only public.{q(r['t'])} add constraint {q(r['n'])} {r['def']};"
        out.append(
            "do $$ begin\n"
            f"  if not exists (select 1 from pg_constraint where conname = {lit(r['n'])} and conrelid = 'public.{q(r['t'])}'::regclass) then\n"
            f"    execute {dollar(stmt, 'c')};\n  end if;\nend $$;"
        )
    return out


def indexes(c):
    out = []
    for i in c["indexes"]:
        out.append(re.sub(r"^CREATE (UNIQUE )?INDEX ", lambda m: f"CREATE {m.group(1) or ''}INDEX IF NOT EXISTS ", i["def"]) + ";")
    return out


def views(c):
    by = {v["n"]: v for v in c["views"]}
    done, order = set(), []

    def visit(n, stack=()):
        if n in done or n not in by:
            return
        if n in stack:
            sys.exit(f"view dependency cycle at {n}")
        for d in by[n]["deps"] or []:
            visit(d, stack + (n,))
        done.add(n)
        order.append(by[n])

    for n in sorted(by):
        visit(n)
    out = []
    for v in order:
        opts = f" with ({', '.join(v['opts'])})" if v["opts"] else ""
        if v["kind"] == "m":
            out.append(f"create materialized view if not exists public.{q(v['n'])}{opts} as\n{v['def'].rstrip(';')}\nwith no data;\n")
        else:
            out.append(f"create or replace view public.{q(v['n'])}{opts} as\n{v['def'].rstrip().rstrip(';')};\n")
    return out


def triggers(c):
    out = []
    for t in c["triggers"]:
        rel = f"{t['s']}.{q(t['t'])}"
        if t["def"].startswith("CREATE CONSTRAINT TRIGGER"):
            out.append(
                "do $$ begin\n"
                f"  if not exists (select 1 from pg_trigger where tgname = {lit(t['n'])} and tgrelid = '{rel}'::regclass) then\n"
                f"    execute {dollar(t['def'], 't')};\n  end if;\nend $$;"
            )
        else:
            out.append(t["def"].replace("CREATE TRIGGER", "CREATE OR REPLACE TRIGGER", 1) + ";")
        if t["enabled"] == "D":
            out.append(f"alter table {rel} disable trigger {q(t['n'])};")
        elif t["enabled"] in ("R", "A"):
            mode = "replica" if t["enabled"] == "R" else "always"
            out.append(f"alter table {rel} enable {mode} trigger {q(t['n'])};")
    return out


CMD = {"r": "select", "a": "insert", "w": "update", "d": "delete", "*": "all"}


def policies(c):
    out = []
    for t in c["tables"]:
        if t["rls"]:
            out.append(f"alter table public.{q(t['n'])} enable row level security;")
        if t["force"]:
            out.append(f"alter table public.{q(t['n'])} force row level security;")
    out.append("")
    for p in c["policies"]:
        rel = f"{p['s']}.{q(p['t'])}"
        roles = ", ".join("public" if r == "public" else q(r) for r in (p["roles"] or ["public"]))
        stmt = f"create policy {q(p['n'])} on {rel} as {'permissive' if p['perm'] else 'restrictive'} for {CMD[p['cmd']]} to {roles}"
        if p["using"] is not None:
            stmt += f"\n  using ({p['using']})"
        if p["check"] is not None:
            stmt += f"\n  with check ({p['check']})"
        out.append(f"drop policy if exists {q(p['n'])} on {rel};\n{stmt};\n")
    return out


PRIV = {"r": "select", "a": "insert", "w": "update", "d": "delete", "D": "truncate", "x": "references",
        "t": "trigger", "m": "maintain", "X": "execute", "U": "usage", "C": "create"}
API_ROLES = ["anon", "authenticated", "service_role"]


def parse_acl(item):
    grantee, rest = item.split("=", 1)
    privs = rest.split("/", 1)[0]
    plain, grant = [], []
    i = 0
    while i < len(privs):
        p = privs[i]
        g = i + 1 < len(privs) and privs[i + 1] == "*"
        (grant if g else plain).append(p)
        i += 2 if g else 1
    return grantee or "public", plain, grant


def grant_lines(kind, target, acl, owner="postgres"):
    """Reproduce an object's ACL exactly. A null ACL means the built-in default."""
    out = [f"revoke all on {kind} {target} from public, {', '.join(API_ROLES)};"]
    if acl is None:
        if kind == "function":
            out.append(f"grant execute on function {target} to public;")
        return out
    for item in acl:
        grantee, plain, grant = parse_acl(item)
        if grantee == owner:
            continue
        who = "public" if grantee == "public" else q(grantee)
        for privs, suffix in ((plain, ""), (grant, " with grant option")):
            names = [PRIV[p] for p in privs]
            std = [n for n in names if n != "maintain"]
            if std:
                out.append(f"grant {', '.join(std)} on {kind} {target} to {who}{suffix};")
            if "maintain" in names:
                # MAINTAIN exists from Postgres 17 (production); skip it on older local servers.
                out.append(
                    f"do $$ begin if current_setting('server_version_num')::int >= 170000 then "
                    f"execute 'grant maintain on {kind} {target} to {who}{suffix}'; end if; end $$;"
                )
    return out


def grants(c):
    out = []
    for t in c["tables"]:
        out += grant_lines("table", f"public.{q(t['n'])}", t["acl"])
    for v in c["views"]:
        out += grant_lines("table", f"public.{q(v['n'])}", v["acl"])
    for s in c["sequences"]:
        out += grant_lines("sequence", f"public.{q(s['n'])}", s["acl"])
    for f in c["functions"]:
        kind = "procedure" if f["kind"] == "p" else "function"
        out += grant_lines(kind, f"public.{q(f['n'])}({f['args']})", f["acl"])
    return out


def storage(c):
    out = []
    for b in c["buckets"]:
        mime = "null" if b["mime"] is None else "array[" + ", ".join(lit(m) for m in b["mime"]) + "]::text[]"
        size = "null" if b["size"] is None else str(b["size"])
        out.append(
            "insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)\n"
            f"values ({lit(b['id'])}, {lit(b['name'])}, {str(b['public']).lower()}, {size}, {mime})\n"
            "on conflict (id) do update set name = excluded.name, public = excluded.public,\n"
            "  file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;"
        )
    out.append("")
    pubs = sorted({p["pub"] for p in c["publication"]})
    for pub in pubs:
        out.append(
            "do $$ begin\n"
            f"  if not exists (select 1 from pg_publication where pubname = {lit(pub)}) then\n"
            f"    create publication {q(pub)};\n  end if;\nend $$;"
        )
    for p in c["publication"]:
        out.append(
            "do $$ begin\n"
            f"  if not exists (select 1 from pg_publication_tables where pubname = {lit(p['pub'])} and schemaname = 'public' and tablename = {lit(p['t'])}) then\n"
            f"    alter publication {q(p['pub'])} add table public.{q(p['t'])};\n  end if;\nend $$;"
        )
    return out


def seed():
    data = json.loads(SEED.read_text(encoding="utf-8"))
    out = ["-- Rows a new, empty ERP needs to boot. No business data.", ""]
    for table, spec in data.items():
        rows = spec["rows"]
        conflict = spec.get("conflict", "do nothing")
        out.append(f"-- {table}: {spec['why']}")
        cols = ", ".join(q(k) for k in rows[0])
        out.append(
            f"insert into public.{q(table)} ({cols})\n"
            f"select {cols} from json_populate_recordset(null::public.{q(table)}, {dollar(json.dumps(rows, ensure_ascii=False, indent=1), 'seed')})\n"
            f"on conflict {conflict};\n"
        )
    return out


def main():
    c = load()
    write("00_extensions.sql", extensions())
    write("01_types.sql", types(c))
    write("02_sequences.sql", sequences(c))
    write("03_tables.sql", tables(c))
    write("04_functions.sql", functions(c))
    write("05_defaults.sql", defaults(c))
    write("06_constraints.sql", constraints(c))
    write("07_indexes.sql", indexes(c))
    write("08_views.sql", views(c))
    write("09_triggers.sql", triggers(c))
    write("10_rls_policies.sql", policies(c))
    write("11_grants.sql", grants(c))
    write("12_storage_realtime.sql", storage(c))
    write("13_seed.sql", seed())


if __name__ == "__main__":
    main()
