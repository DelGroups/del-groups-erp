/**
 * Writes supabase/scripts/tenant1_migration_history.sql (prompt 11):
 *
 *   npm run tenants:history-sql
 *
 * The Del Groups database was built by hand, so it may have no (or an incomplete)
 * supabase_migrations.schema_migrations. migrate-all needs it to know what is applied.
 * Everything up to supabase/baseline/VERSION is in production by definition (the baseline
 * IS the production snapshot), so those files are recorded as applied. Newer files are
 * left out on purpose: migrate-all applies them (they are written to be re-runnable).
 * tests/tenant1Cutover.test.mjs fails when the committed file is out of date.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const HISTORY_SQL_PATH = path.join(ROOT, "supabase", "scripts", "tenant1_migration_history.sql");

export function migrationHistorySql(sqlDir: string): string {
  const version = readFileSync(path.join(sqlDir, "baseline", "VERSION"), "utf8").trim();
  const rows = readdirSync(path.join(sqlDir, "migrations"))
    .sort()
    .flatMap((f) => {
      const m = /^(\d{14})_([a-z0-9_]+)\.sql$/.exec(f);
      return m && m[1] <= version ? [`  ('${m[1]}', '${m[2]}')`] : [];
    });
  return [
    "-- GENERATED by scripts/tenants/migration-history.ts (npm run tenants:history-sql). Do not edit.",
    "--",
    "-- Tenant #1 cutover (prompt 11), step 5: records in the Del Groups database that every",
    `-- migration up to the baseline version ${version} is applied (the baseline is the production`,
    "-- snapshot). Newer files are not listed: the tenant-migrations workflow applies them.",
    "-- Creates supabase_migrations.schema_migrations if it is missing, as `supabase db push` would.",
    "-- Adds rows only (on conflict do nothing); touches no ERP table. Safe to re-run.",
    "",
    "create schema if not exists supabase_migrations;",
    "create table if not exists supabase_migrations.schema_migrations (",
    "  version text primary key,",
    "  statements text[],",
    "  name text",
    ");",
    "",
    "insert into supabase_migrations.schema_migrations (version, name) values",
    rows.join(",\n"),
    "on conflict (version) do nothing;",
    "",
    `select count(*) as recorded_up_to_${version} from supabase_migrations.schema_migrations where version <= '${version}';`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(HISTORY_SQL_PATH, migrationHistorySql(path.join(ROOT, "supabase")));
  console.log(`wrote ${path.relative(ROOT, HISTORY_SQL_PATH)}`);
}
