export const LOCALES = ["az", "en", "ru"] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = "az";

export const MESSAGES: Record<Locale, Messages> = { az, en, ru };

/** Looks up "a.b.c" and fills {placeholders}; returns the key itself when it is missing. */
export function translate(messages: Messages, key: string, vars?: Record<string, string | number>): string {
  let node: unknown = messages;
  for (const part of key.split(".")) {
    node = node && typeof node === "object" ? (node as Record<string, unknown>)[part] : undefined;
  }
  if (typeof node !== "string") return key;
  return vars ? node.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : node;
}

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}
